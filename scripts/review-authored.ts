// Writes data/conversation/authored-review.md: every authored Talk line grouped by unit, with a
// checkbox for the owner. Tick a line by adding `ownerReviewed` (YYYY-MM-DD) to its JSON row; this
// sheet then shows it as checked. `npm run review:authored`.
import { readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { parseConversationSeed } from "./validate-conversation.ts";

const DIR = "data/conversation";
const OUT = join(DIR, "authored-review.md");

export async function buildAuthoredReview(dir = DIR): Promise<string> {
  const files = (await readdir(dir)).filter((file) => file.startsWith("unit-") && file.endsWith(".json")).sort();
  // SAFETY: JSON.parse returns any; parseConversationSeed validates the shape before use.
  const docs = await Promise.all(files.map(async (file) => parseConversationSeed(JSON.parse(await readFile(join(dir, file), "utf8")) as unknown)));
  const units = docs.flatMap((doc) => doc.units).sort((a, b) => a.ord - b.ord);
  const chunks = docs.flatMap((doc) => doc.chunks).filter((chunk) => chunk.sourceKind === "authored");
  const templates = docs.flatMap((doc) => doc.templates ?? []);
  const reviewed = chunks.filter((chunk) => chunk.ownerReviewed).length + templates.filter((template) => template.ownerReviewed).length;
  const lines = [
    "# Authored Talk lines: owner review sheet",
    "",
    `Generated by \`npm run review:authored\`; do not edit by hand. ${reviewed}/${chunks.length + templates.length} reviewed.`,
    "To mark a line reviewed, add `\"ownerReviewed\": \"YYYY-MM-DD\"` to its row in `unit-NN.json` and regenerate.",
    "",
  ];
  for (const unit of units) {
    const own = chunks.filter((chunk) => chunk.unitOrd === unit.ord).sort((a, b) => a.ord - b.ord);
    const ownTemplates = templates.filter((template) => template.unitOrd === unit.ord).sort((a, b) => a.ord - b.ord);
    if (own.length === 0 && ownTemplates.length === 0) continue;
    lines.push(`## Unit ${unit.ord}: ${unit.titleKo}`, "");
    for (const chunk of own) {
      lines.push(`- [${chunk.ownerReviewed ? "x" : " "}] \`${chunk.key}\` (${chunk.role}, ${chunk.register}, ${chunk.authoredScope ?? "?"}, written ${chunk.authoredOn ?? "?"})`);
      lines.push(`  - ${chunk.text}`, `  - ${chunk.kana}`, `  - cue: ${chunk.cueKo}`);
      if (chunk.noteKo) lines.push(`  - note: ${chunk.noteKo}`);
      if (chunk.reviewNote) lines.push(`  - checked: ${chunk.reviewNote}`);
    }
    for (const template of ownTemplates) {
      lines.push(`- [${template.ownerReviewed ? "x" : " "}] \`${template.key}\` (template, ${template.register}, written ${template.authoredOn})`);
      lines.push(`  - ${template.jaTemplate}`, `  - ${template.kanaTemplate}`, `  - cue: ${template.cueKo}`);
      lines.push(`  - slots: ${template.slots.map((slot) => `${slot.ja}（${slot.kana}）${slot.meaningKo}`).join(", ")}`);
      lines.push(`  - checked: ${template.reviewNote}`);
    }
    lines.push("");
  }
  return `${lines.join("\n")}\n`;
}

if (process.argv[1]?.endsWith("review-authored.ts")) {
  const markdown = await buildAuthoredReview();
  await writeFile(OUT, markdown);
  console.log(`Wrote ${OUT}`);
}
